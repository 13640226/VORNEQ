import assert from 'node:assert/strict';
import {safelyReadRunnerArtifacts} from './v5-safe-artifact-access.mjs';
import {observeAfterCleanup} from './v5-runtime-integration.mjs';
import {inspectLighthouseReport,runWithIntegrityRetries,sanitizeAttemptDiagnostics} from './lighthouse-integrity.mjs';
const lhr={audits:{'largest-contentful-paint':{numericValue:1000},'cumulative-layout-shift':{numericValue:0.01}},categories:{performance:{score:0.9}}};
const bad={...lhr,runtimeError:{code:'NO_NAVSTART'}};
const hostile={lhr};Object.defineProperty(hostile,'artifacts',{get(){throw Error('SECRET_ARTIFACT_GETTER');}});
assert.equal(safelyReadRunnerArtifacts(hostile),undefined);
assert.equal(safelyReadRunnerArtifacts(null),undefined);
assert.equal(safelyReadRunnerArtifacts({artifacts:{Trace:{traceEvents:[]}}}).Trace.traceEvents.length,0);
let sequence=[];
const outcome=await observeAfterCleanup(async()=>{sequence.push('core');try{return {lhr:hostile.lhr,runnerArtifacts:safelyReadRunnerArtifacts(hostile),attemptDiagnostics:{}};}finally{sequence.push('cleanup');}},()=>sequence.push('scan'));
assert.deepEqual(sequence,['core','cleanup','scan']);
assert.equal(inspectLighthouseReport(outcome.lhr).status,'VALID');
assert.equal(outcome.attemptDiagnostics.v5Trace.navigationStart,'unknown');
assert.ok(!JSON.stringify(sanitizeAttemptDiagnostics(outcome.attemptDiagnostics)).includes('SECRET'));
let attempts=0;sequence=[];
const result=await runWithIntegrityRetries({maxAttempts:2,executeAttempt:()=>observeAfterCleanup(async()=>{const i=++attempts;sequence.push('core'+i);try{return {lhr:i===1?bad:lhr,runnerArtifacts:safelyReadRunnerArtifacts(hostile),attemptDiagnostics:{}};}finally{sequence.push('cleanup'+i);}},()=>sequence.push('scan'+attempts))});
assert.equal(result.status,'VALID');assert.equal(result.attempts,2);
assert.deepEqual(sequence,['core1','cleanup1','scan1','core2','cleanup2','scan2']);
let failed=0;await assert.rejects(runWithIntegrityRetries({maxAttempts:2,isRecoverableError:()=>true,executeAttempt:()=>observeAfterCleanup(async()=>{failed++;throw Error('Lighthouse rejection');})}));assert.equal(failed,2);
await assert.rejects(observeAfterCleanup(async()=>{throw Error('Cleanup failed');}),/Cleanup failed/);
console.log('PASS guarded artifact getter, verdict, cleanup, retry, rejection, redaction');
